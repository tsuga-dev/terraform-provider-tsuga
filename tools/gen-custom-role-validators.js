#!/usr/bin/env node

/**
 * Generates the asset type lists of the hand-written tsuga_custom_role resource
 * schema (internal/resource_custom_role/validators_gen.go) from the OpenAPI spec,
 * so the keys the API accepts in `assets`, and which of them only accept `read`,
 * stay in sync with the API without hand-copying them.
 *
 * `assets` is a closed object whose property names are the asset types and whose
 * values are `read` or `read`/`write` enums. The create body, the update body and
 * the CustomRole response schema must agree, or generation fails loudly.
 */
const fs = require("fs");
const path = require("path");

const specPath = process.argv[2] || "./public-open-api.json";
const spec = JSON.parse(fs.readFileSync(specPath, "utf8"));

function fail(msg) {
  console.error(`gen-custom-role-validators: ${msg}`);
  process.exit(1);
}

function requestAssets(pathKey, method) {
  const op = spec.paths[pathKey] && spec.paths[pathKey][method];
  if (!op) fail(`${method.toUpperCase()} ${pathKey} not found in spec`);
  const assets = op.requestBody.content["application/json"].schema.properties.assets;
  if (!assets) fail(`${method.toUpperCase()} ${pathKey} has no assets property`);
  return assets;
}

const responseAssets = spec.components.schemas.CustomRole && spec.components.schemas.CustomRole.properties.assets;
if (!responseAssets) fail("CustomRole.assets not found in spec");

const sources = [
  ["POST /v1/custom-roles", requestAssets("/v1/custom-roles", "post")],
  ["PUT /v1/custom-roles/{id}", requestAssets("/v1/custom-roles/{id}", "put")],
  ["CustomRole", responseAssets],
];
const [[baseName, base], ...others] = sources;
for (const [name, node] of others) {
  if (JSON.stringify(node) !== JSON.stringify(base)) fail(`${baseName} and ${name} disagree on assets`);
}
if (base.additionalProperties !== undefined && base.additionalProperties !== false) {
  fail("assets accepts additional properties; the generated key list would reject valid keys");
}

const assetTypes = Object.keys(base.properties);
const readOnlyAssetTypes = [];
for (const [assetType, property] of Object.entries(base.properties)) {
  const levels = JSON.stringify(property.enum);
  if (levels === JSON.stringify(["read"])) {
    readOnlyAssetTypes.push(assetType);
  } else if (levels !== JSON.stringify(["read", "write"])) {
    fail(`${assetType}: unexpected access levels ${levels}`);
  }
}

const goStringSlice = (values) => values.map((v) => JSON.stringify(v)).join(", ");

const lines = [
  "// Code generated by tools/gen-custom-role-validators.js; DO NOT EDIT.",
  "package resource_custom_role",
  "",
  `var assetTypes = []string{${goStringSlice(assetTypes)}}`,
  "",
  `var readOnlyAssetTypes = []string{${goStringSlice(readOnlyAssetTypes)}}`,
  "",
];
fs.writeFileSync(path.join(process.cwd(), "internal/resource_custom_role/validators_gen.go"), lines.join("\n"));
console.log("gen-custom-role-validators: wrote validators_gen.go");
